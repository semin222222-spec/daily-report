export interface RecipeIngredient {
  name: string
  amount: string
}

export interface RecipePrep {
  name: string
  detail: string
}

export interface Recipe {
  slug: string
  name: string
  category: string
  ingredients: RecipeIngredient[]
  garnish?: string
  sauce?: string
  steps: string[]
  notes: string[]
  prep: RecipePrep[]
}

export interface RecipeCategory {
  slug: string
  no: string
  name: string
}

export const RECIPE_CATEGORIES: RecipeCategory[] = [
  { slug: 'yukhoe', no: '01', name: '육회' },
  { slug: 'main', no: '02', name: '메인요리' },
  { slug: 'noodle', no: '03', name: '면·파스타' },
  { slug: 'nabe', no: '04', name: '나베·전골·찌개' },
  { slug: 'bunsik', no: '05', name: '분식' },
  { slug: 'jeon', no: '06', name: '전·구이' },
  { slug: 'fried', no: '07', name: '튀김·스낵' },
  { slug: 'dessert', no: '08', name: '디저트' },
]

export function recipeCategory(slug: string): RecipeCategory | undefined {
  return RECIPE_CATEGORIES.find((c) => c.slug === slug)
}

function ing(pairs: [string, string][]): RecipeIngredient[] {
  return pairs.map(([name, amount]) => ({ name, amount }))
}

